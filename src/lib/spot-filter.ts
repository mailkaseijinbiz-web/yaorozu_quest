// 新興宗教（カルト含む）の施設を「場（Spot）」から除外するための共有フィルタ。
//
// 方針: 八百万クエストの「場」は、地域に根ざした神社・寺院（伝統的な信仰の場）を対象とする。
// OSM(OpenStreetMap) には新興宗教の教会・会館も "place_of_worship" として登録されており、
// 旧シードや GPS 生成で混入しうるため、名称ベースで明示的に除外する。
//
// 適用箇所（3か所）:
//   1. src/data/tokyo-spots.ts  … シード生成時にスキップ（保存自体しない）
//   2. src/lib/db.ts getSpots() … 既存スナップショットを読み取り時に退役（ソフト削除）
//   3. src/lib/overpass.ts      … GPS 周辺の実在スポット取得時に除外
//
// 注意: 神社/寺院の正規名（例「真光寺」「金光寺」）を誤って巻き込まないよう、
// 団体を特定できる十分に固有なトークンのみを並べている（単独の「真光」等は使わない）。
const EXCLUDED_RELIGION_PATTERNS: RegExp[] = [
  // 日本の主な新宗教・教団
  /創価学会|創価/,
  /立正佼成会/,
  /霊友会/,
  /真如苑/,
  /阿含宗/,
  /幸福の科学|エル・?カンターレ/,
  /天理教/,
  /顕正会/,
  /生長の家/,
  /金光教/,
  /世界救世(教)?/,
  /崇教真光|真光文明|世界真光/,
  /ワールドメイト|World ?Mate/i,
  /GLA(?![A-Za-z])/, // GLA総合本部 等（語境界で誤検出を抑制）
  /PL教団|パーフェクト ?リバティ/,
  /妙智会|妙智會/,
  /念法眞教|念法真教/,
  /佛所護念|仏所護念/,
  /解脱会/,
  /円応教/,
  // 統一教会（世界平和統一家庭連合）
  /統一教会|家庭連合/,
  // エホバの証人
  /エホバ|ものみの塔|王国会館/,
  // オウム真理教の後継団体
  /オウム真理教|アレフ|ひかりの輪/,
  // 末日聖徒イエス・キリスト教会（モルモン）
  /末日聖徒|モルモン/,
];

/**
 * 場（Spot）の名称が新興宗教の施設に該当するかを判定する。
 * 該当した「場」は一覧・地図・生成のいずれにも出さない。
 */
export function isExcludedReligion(name: string | null | undefined): boolean {
  if (!name) return false;
  return EXCLUDED_RELIGION_PATTERNS.some((re) => re.test(name));
}
