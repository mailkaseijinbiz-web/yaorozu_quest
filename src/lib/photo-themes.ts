// 「写真を撮ろう」タスクの撮影テーマ。場のカテゴリから2〜3個の具体的な被写体を返す。
// 純ロジック（副作用なし・テスト対象）。証拠写真モーダルでの「お題」提示と、
// photo-feedback API への文脈補強に使う。
// -----------------------------------------------------------------------------

// カテゴリ別の撮影テーマ候補。先頭2〜3個を提示する。部分一致で判定する
// （「○○神社」「△△寺」など固有名を含むカテゴリにも当たるように）。
const THEMES: { match: string[]; themes: string[] }[] = [
  { match: ['神社', '社', '宮', '稲荷'], themes: ['鳥居の連なり', '狛犬の表情', '本殿・拝殿のたたずまい'] },
  { match: ['寺', '院', '大師', '不動'], themes: ['山門・仁王像', '本堂の屋根や彫刻', '香炉やお地蔵さま'] },
  { match: ['公園', '緑地', '庭園', '広場'], themes: ['季節の草花や木立', '空と広がりのある景色', '人々の何気ない営み'] },
  { match: ['商店街', '市場', '横丁'], themes: ['看板やのれんの意匠', '路地の奥行き', '店先のにぎわい'] },
  { match: ['飲食', '食堂', 'カフェ', 'レストラン', '居酒屋'], themes: ['一皿の彩り', '店内の灯りと雰囲気', 'メニューや看板'] },
  { match: ['商業施設', '百貨店', 'モール', '店'], themes: ['建物の外観', 'ショーウィンドウ', '人の流れ'] },
  { match: ['駅', '橋', '川', '坂', '道'], themes: ['構造物のフォルム', '光と影のコントラスト', '行き交う風景'] },
  { match: ['城', '史跡', '記念', '碑'], themes: ['石垣や遺構のディテール', '全景のスケール感', '案内板や刻まれた文字'] },
];

const DEFAULT_THEMES = ['その場で心を動かした光景', '見落とされがちなディテール', '空と建物の重なり'];

/**
 * 場のカテゴリから撮影テーマ候補（2〜3個）を返す。一致しなければ汎用テーマ。
 * 同じカテゴリには常に同じテーマを返す（決め打ち・安定）。
 */
export function photoThemesFor(category: string | undefined): string[] {
  if (category) {
    for (const entry of THEMES) {
      if (entry.match.some((m) => category.includes(m))) return entry.themes;
    }
  }
  return DEFAULT_THEMES;
}
