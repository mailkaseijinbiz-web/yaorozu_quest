/** 情報源の種別（提供してもらった参照元の分類に対応） */
export type TriviaSourceType =
  | 'さんたつ'
  | 'note街歩きタグ'
  | '自治体ウォーキングマップ'
  | '地形・歴史系サイト';

export interface TriviaSource {
  type: TriviaSourceType;
  /** 情報源の名称や運営主体（例: 「散歩の達人」「東京スリバチ学会」） */
  name: string;
  url?: string;
}

export interface Trivia {
  id: string;
  /** 豆知識のタイトル（一覧で見出しになる短い一文） */
  title: string;
  /** 豆知識の本文。散歩中に「へぇ」となる粒度で */
  body: string;
  area: TriviaArea;
  themes: TriviaTheme[];
  /** 最寄りの目印・ランドマーク（任意） */
  landmark?: string;
  /** おおよその位置（任意・地図表示用） */
  latitude?: number;
  longitude?: number;
  /** 散歩中の楽しみ方・観察ポイント */
  walkTips: string[];
  /** どの種別の情報源で語られがちか */
  sources: TriviaSource[];
}

